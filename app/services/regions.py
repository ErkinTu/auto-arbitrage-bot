_PREFIX_RE = re.compile(
    r"^(?:с\.?|c\.?|село|пос\.?|посёлок|поселок|г\.?|д\.?|дер\.?|аил|айыл)\s+"
)
_PAREN_RE = re.compile(r"\s*\([^)]*\)")


def _canon(city: str) -> str:
    """Каноническая форма названия: нижний регистр, ё→е, без префикса типа
    населённого пункта, схлопнутые пробелы (скобки сохраняются для точного матча)."""
    s = city.strip().lower().replace("ё", "е")
    s = _PREFIX_RE.sub("", s)
    return re.sub(r"\s+", " ", s).strip()


def is_foreign(city: str | None) -> bool:
    """Объявление из-за рубежа: в поле города источник записал страну.

    Живёт здесь, а не в `bot/matching.py`, потому что нужно и статистике
    (`services/stats.py`), а та не может импортировать бота без цикла.
    """
    return city is not None and city.strip() in FOREIGN_LOCATIONS


def region_of(city: str | None) -> str | None:
    """Регион населённого пункта или None, если город неизвестен/спорный.

    Зарубежные страны (в поле города) → FOREIGN. Порядок важен: страна
    «Люксембург» отсекается до того, как «с. Люксембург» (село в Чуе) уйдёт в карту.
    """
    if city is None:
        return None
    raw = city.strip()
    if not raw:
        return None
    if raw in FOREIGN_LOCATIONS:
        return FOREIGN
    key = _canon(raw)
    if key in _CITY_TO_REGION:
        return _CITY_TO_REGION[key]
    base = _PAREN_RE.sub("", key).strip()
    if base != key and base in _CITY_TO_REGION:
        return _CITY_TO_REGION[base]
    return None


def region_matches(city: str | None, region_code: str) -> bool:
    """Проходит ли город объявления под выбранный регион фильтра (region_code≠None).

    LOCAL («Местный рынок») — любой НЕ-зарубежный город, включая нераспознанные
    сёла (так же, как старое skip_foreign считало неизвестный город местным).
    Прочие коды — точное совпадение региона города (неизвестный/спорный = не проходит).
    """
    if region_code == LOCAL:
        return region_of(city) != FOREIGN
    return region_of(city) == region_code
